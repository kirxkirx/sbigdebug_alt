// cName maps our layout names to C expressions (some C typedefs are anonymous
// nested structs or shared typedefs).
var cTypeOverride = map[string]string{
	"READOUT_INFO": "READOUT_INFO",
}

// TestABILayoutsConsistent checks the table itself (fields inside the struct, aligned, no overlap).
func TestABILayoutsConsistent(t *testing.T) {
	for _, l := range abiLayouts {
		type iv struct{ a, b int }
		var spans []iv
		for _, n := range l.order {
			f := l.fields[n]
			if f.off < 0 || f.off+f.size > l.size {
				t.Errorf("%s.%s outside struct", l.name, n)
			}
			if f.size > 1 && f.off%f.size != 0 {
				t.Errorf("%s.%s misaligned (off %d size %d)", l.name, n, f.off, f.size)
			}
			spans = append(spans, iv{f.off, f.off + f.size})
		}
		sort.Slice(spans, func(i, j int) bool { return spans[i].a < spans[j].a })
		for i := 1; i < len(spans); i++ {
			if spans[i].a < spans[i-1].b {
				t.Errorf("%s: overlapping fields", l.name)
			}
		}
	}
}

// TestGenerateABICheck writes a C file with _Static_assert()s for every offset
// and size in abi.go. CI compiles it against the vendor sbigudrv.h with clang for
// i686-pc-windows-msvc and x86_64-pc-windows-msvc (see .github/workflows).
func TestGenerateABICheck(t *testing.T) {
	out := os.Getenv("SBIG_ABI_CHECK_OUT")
	if out == "" {
		t.Skip("set SBIG_ABI_CHECK_OUT=path.c to generate the C ABI check")
	}
	var b strings.Builder
	b.WriteString("/* generated by abi_test.go - compile with clang -fsyntax-only for Windows targets */\n")
	b.WriteString("#include <stddef.h>\n#include \"sbigudrv.h\"\n\n")
	for _, l := range abiLayouts {
		ct := l.name
		if o, ok := cTypeOverride[l.name]; ok {
			ct = o
		}
		fmt.Fprintf(&b, "_Static_assert(sizeof(%s) == %d, \"sizeof %s\");\n", ct, l.size, l.name)
		for _, n := range l.order {
			fmt.Fprintf(&b, "_Static_assert(offsetof(%s, %s) == %d, \"%s.%s\");\n", ct, n, l.fields[n].off, l.name, n)
		}
	}
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestBCD(t *testing.T) {
	if v := bcd(0x0900); v != 9.0 {
		t.Errorf("bcd(0x900)=%v", v)
	}
	if v := bcd(0x0080); v != 0.8 {
		t.Errorf("bcd(0x80)=%v", v)
	}
}
